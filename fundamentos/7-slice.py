bookTitle = "Game of Thrones"
# string[begin:final] - index start in 0 | final index - 1

# 1 - Search all the string by the first position
print(bookTitle[0:])

# 2 - Search all the string until the last position
print(bookTitle[:16])

# 3 - Search all the string by the third until the last position
print(bookTitle[2:])

# 4 - Search all the string 2 by 2 
print(bookTitle[::2])

# 5 - Search all the string by the odd index
print(bookTitle[1::2])

# 6 - Reverse the string
print(bookTitle[::-1])
